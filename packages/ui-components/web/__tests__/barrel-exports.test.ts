describe("barrel 导出契约", () => {
  for (const [group, names] of Object.entries(EXPECTED_EXPORTS)) {
    test(`${group} 分组的导出都能从 barrel 取到`, () => {
      for (const name of names) {
        expect(Object.hasOwn(barrel, name), `${group} 分组缺少导出：${name}`).toBe(true);
      }
    });
  }

  test("barrel 的运行时导出均非空", () => {
    for (const [name, value] of Object.entries(barrel)) {
      expect(value, `${name} 的导出值为 null`).not.toBeNull();
      expect(value, `${name} 的导出值为 undefined`).not.toBeUndefined();
      if (typeof value === "string") {
        expect(value.length, `${name} 的导出值为空字符串`).toBeGreaterThan(0);
      }
    }
  });

  test("barrel 的运行时导出总数与期望清单一致", () => {
    const expectedTotal = Object.values(EXPECTED_EXPORTS).reduce((sum, names) => sum + names.length, 0);
    expect(Object.keys(barrel).length, "导出数量已变化，请同步 EXPECTED_EXPORTS").toBe(expectedTotal);
  });
});
