import { describe, expect, test } from "bun:test";

import { describeCron, PRESETS } from "../pages/agent-panel/components/CronEditor";

const translatePreset = (key: string) => `翻译:${key}`;

describe("CronEditor describeCron 高覆盖纯逻辑", () => {
  // 分钟步长分支仅读取 cron 的第一个字段，覆盖常用边界和不同剩余字段组合。
  test.each([
    ["一分钟", "*/1 * * * *", "每 1 分钟"],
    ["两分钟", "*/2 * * * *", "每 2 分钟"],
    ["三分钟", "*/3 * * * *", "每 3 分钟"],
    ["四分钟", "*/4 * * * *", "每 4 分钟"],
    ["六分钟", "*/6 * * * *", "每 6 分钟"],
    ["十分钟", "*/10 * * * *", "每 10 分钟"],
    ["十二分钟", "*/12 * * * *", "每 12 分钟"],
    ["二十分钟", "*/20 * * * *", "每 20 分钟"],
    ["三十分钟", "*/30 * * * *", "每 30 分钟"],
    ["四十五分钟", "*/45 * * * *", "每 45 分钟"],
    ["五十九分钟", "*/59 * * * *", "每 59 分钟"],
    ["指定小时", "*/7 8 * * *", "每 7 分钟"],
    ["指定日期", "*/8 9 2 * *", "每 8 分钟"],
    ["指定月份", "*/9 10 3 4 *", "每 9 分钟"],
    ["指定星期", "*/11 11 * * 1", "每 11 分钟"],
  ])("格式化分钟步长：%s", (_name, cron, expected) => {
    expect(describeCron(cron, translatePreset)).toBe(expected);
  });

  // 每日分支转换为中文十二小时制，并保留分钟补零与通配符语义。
  test.each([
    ["凌晨一点", "0 1 * * *", "每天上午 1:00"],
    ["凌晨两点", "2 2 * * *", "每天上午 2:02"],
    ["凌晨三点", "3 3 * * *", "每天上午 3:03"],
    ["凌晨四点", "4 4 * * *", "每天上午 4:04"],
    ["凌晨五点", "5 5 * * *", "每天上午 5:05"],
    ["上午六点", "6 6 * * *", "每天上午 6:06"],
    ["上午七点", "7 7 * * *", "每天上午 7:07"],
    ["上午八点", "8 8 * * *", "每天上午 8:08"],
    ["上午十点", "9 10 * * *", "每天上午 10:09"],
    ["上午十一点", "10 11 * * *", "每天上午 11:10"],
    ["正午带分钟", "11 12 * * *", "每天中午 12:11"],
    ["下午一点", "12 13 * * *", "每天下午 1:12"],
    ["下午两点", "13 14 * * *", "每天下午 2:13"],
    ["下午三点", "14 15 * * *", "每天下午 3:14"],
    ["下午四点", "15 16 * * *", "每天下午 4:15"],
    ["下午五点", "16 17 * * *", "每天下午 5:16"],
    ["下午六点", "17 18 * * *", "每天下午 6:17"],
    ["下午七点", "18 19 * * *", "每天下午 7:18"],
    ["下午十点", "19 22 * * *", "每天下午 10:19"],
    ["下午十一点", "20 23 * * *", "每天下午 11:20"],
  ])("格式化每日计划：%s", (_name, cron, expected) => {
    expect(describeCron(cron, translatePreset)).toBe(expected);
  });

  // 每周分支需要将单日、离散日和连续范围稳定转换为星期名称。
  test.each([
    ["周日", "1 1 * * 0", "每周日上午 1:01"],
    ["周一", "2 2 * * 1", "每周一上午 2:02"],
    ["周二", "3 3 * * 2", "每周二上午 3:03"],
    ["周三", "4 4 * * 3", "每周三上午 4:04"],
    ["周四", "5 5 * * 4", "每周四上午 5:05"],
    ["周五", "6 6 * * 5", "每周五上午 6:06"],
    ["周六", "7 7 * * 6", "每周六上午 7:07"],
    ["上午离散日", "8 8 * * 0,2", "每周日、二上午 8:08"],
    ["上午三日", "9 9 * * 1,2,3", "每周一、二、三上午 9:09"],
    ["上午四日", "10 10 * * 2,3,4,5", "每周二、三、四、五上午 10:10"],
    ["上午五日", "11 11 * * 0,1,2,3,4", "每周日、一、二、三、四上午 11:11"],
    ["正午周日", "12 12 * * 0", "每周日中午 12:12"],
    ["下午周一", "13 13 * * 1", "每周一下午 1:13"],
    ["下午周二", "14 14 * * 2", "每周二下午 2:14"],
    ["下午周三", "15 15 * * 3", "每周三下午 3:15"],
    ["下午周四", "16 16 * * 4", "每周四下午 4:16"],
    ["下午周五", "17 17 * * 5", "每周五下午 5:17"],
    ["下午周六", "18 18 * * 6", "每周六下午 6:18"],
    ["完整星期范围", "19 19 * * 0-6", "每周日、一、二、三、四、五、六下午 7:19"],
    ["工作周范围", "20 20 * * 1-5", "每周一、二、三、四、五下午 8:20"],
    ["周末范围", "21 21 * * 0-1", "每周日、一下午 9:21"],
    ["中间范围", "22 22 * * 3-5", "每周三、四、五下午 10:22"],
    ["单日通配分钟", "* 23 * * 6", "每周六下午 11"],
    ["范围通配分钟", "* 12 * * 2-3", "每周二、三中午 12"],
    ["前后空白", "  1 6 * * 4  ", "每周四上午 6:01"],
  ])("格式化每周计划：%s", (_name, cron, expected) => {
    expect(describeCron(cron, translatePreset)).toBe(expected);
  });

  // 每月分支优先于年度分支，月份通配符时只显示日期和时刻。
  test.each([
    ["一号凌晨", "1 1 1 * *", "每月 1 号上午 1:01"],
    ["二号上午", "2 2 2 * *", "每月 2 号上午 2:02"],
    ["三号上午", "3 3 3 * *", "每月 3 号上午 3:03"],
    ["十号上午", "10 10 10 * *", "每月 10 号上午 10:10"],
    ["十一号正午", "11 12 11 * *", "每月 11 号中午 12:11"],
    ["十二号下午", "12 13 12 * *", "每月 12 号下午 1:12"],
    ["二十号下午", "20 20 20 * *", "每月 20 号下午 8:20"],
    ["三十号下午", "30 23 30 * *", "每月 30 号下午 11:30"],
    ["三十一号通配分钟", "* 8 31 * *", "每月 31 号上午 8"],
    ["前后空白", "  5 9 9 * * ", "每月 9 号上午 9:05"],
  ])("格式化每月计划：%s", (_name, cron, expected) => {
    expect(describeCron(cron, translatePreset)).toBe(expected);
  });

  // 指定月份时应输出紧凑的年周期描述，并继续使用十二小时制。
  test.each([
    ["一月一日", "1 1 1 1 *", "1月1号上午1:01"],
    ["二月二日", "2 2 2 2 *", "2月2号上午2:02"],
    ["三月三日", "3 3 3 3 *", "3月3号上午3:03"],
    ["四月四日", "4 4 4 4 *", "4月4号上午4:04"],
    ["五月五日", "5 5 5 5 *", "5月5号上午5:05"],
    ["六月正午", "6 12 6 6 *", "6月6号中午12:06"],
    ["七月下午", "7 13 7 7 *", "7月7号下午1:07"],
    ["八月下午", "8 18 8 8 *", "8月8号下午6:08"],
    ["九月深夜", "9 23 9 9 *", "9月9号下午11:09"],
    ["十二月通配分钟", "* 0 31 12 *", "12月31号上午12"],
  ])("格式化年度计划：%s", (_name, cron, expected) => {
    expect(describeCron(cron, translatePreset)).toBe(expected);
  });

  // 不满足五字段或不属于已支持模式的表达式必须安全返回 null，不得抛出异常。
  test.each([
    ["空字符串", ""],
    ["仅空白", "   "],
    ["四字段", "0 1 * *"],
    ["六字段", "0 1 * * * *"],
    ["仅分钟", "0"],
    ["分钟与小时", "0 1"],
    ["通配小时", "1 * * * *"],
    ["通配日期", "0 1 1 * 1"],
    ["通配月份", "0 1 * 1 1"],
    ["非数字小时", "0 abc * * *"],
  ])("拒绝无法描述的 cron：%s", (_name, cron) => {
    expect(() => describeCron(cron, translatePreset)).not.toThrow();
    expect(describeCron(cron, translatePreset)).toBeNull();
  });

  // 纯格式化不得修改预设表或调用方提供的翻译函数以外的任何输入状态。
  test("格式化不会改写预设表", () => {
    const before = { ...PRESETS };
    for (const cron of Object.values(PRESETS)) describeCron(cron, translatePreset);
    expect(PRESETS).toEqual(before);
  });

  test("预设命中只调用一次翻译函数", () => {
    const calls: string[] = [];
    const translator = (key: string) => {
      calls.push(key);
      return key;
    };

    expect(describeCron(PRESETS.every5min, translator)).toBe("cron.presets.every5min");
    expect(calls).toEqual(["cron.presets.every5min"]);
  });
});
